/**
 * Get ground truth for a specific file.
 */
export function getGroundTruth(filename: string): GroundTruthEntry | undefined {
  return GROUND_TRUTH.find((gt) => gt.file === filename);
}

/**
 * Get all entries that have at least one non-null field value.
 * These are the entries useful for accuracy measurement.
 */
export function getVerifiableEntries(): GroundTruthEntry[] {
  return GROUND_TRUTH.filter(
    (gt) =>
      gt.vendorName !== null || gt.total !== null || gt.date !== null || gt.invoiceNumber !== null,
  );
}
